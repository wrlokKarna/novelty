import { and, asc, eq } from 'drizzle-orm';

import {
    chapters,
    characters,
    organizations,
    storyBeats,
} from '../../../shared/schema';
import type {
    NewStoryBeat,
    StoryBeat,
    StoryBeatType,
} from '@/shared/types/project/manuscript';
import type { SQLiteDB } from '@/shared/types/db';

function parseBeat(row: Record<string, unknown>): StoryBeat {
    return {
        id: row.id as string,
        projectId: (row.projectId as string | null) ?? null,
        chapterId: (row.chapterId as string | null) ?? null,
        beatType: (row.beatType as StoryBeatType) ?? 'custom',
        title: row.title as string,
        description: (row.description as string | null) ?? null,
        orderIndex: (row.orderIndex as number) ?? 0,
        inStoryDate: (row.inStoryDate as string | null) ?? null,
        dateOrder: (row.dateOrder as number) ?? 0,
        endInStoryDate: (row.endInStoryDate as string | null) ?? null,
        endDateOrder: (row.endDateOrder as number | null) ?? null,
        entityType: (row.entityType as string | null) ?? null,
        entityId: (row.entityId as string | null) ?? null,
        eventType: (row.eventType as string) ?? 'story_beat',
        metadata: row.metadata ? JSON.parse(row.metadata as string) : null,
        autoGenerated: !!row.autoGenerated,
        createdAt: row.createdAt as Date,
        updatedAt: row.updatedAt as Date,
    };
}

export async function getBeatsByProject(
    db: SQLiteDB,
    projectId: string
): Promise<StoryBeat[]> {
    const rows = await db
        .select()
        .from(storyBeats)
        .where(eq(storyBeats.projectId, projectId))
        .orderBy(asc(storyBeats.dateOrder), asc(storyBeats.orderIndex));
    return rows.map(parseBeat);
}

export async function getBeatById(
    db: SQLiteDB,
    id: string
): Promise<StoryBeat | undefined> {
    const result = await db
        .select()
        .from(storyBeats)
        .where(eq(storyBeats.id, id));
    if (!result[0]) return undefined;
    return parseBeat(result[0] as Record<string, unknown>);
}

export async function createBeat(
    db: SQLiteDB,
    beat: NewStoryBeat
): Promise<StoryBeat> {
    const now = new Date();
    const value = {
        ...beat,
        beatType: beat.beatType ?? 'custom',
        eventType: beat.eventType ?? 'story_beat',
        dateOrder: beat.dateOrder ?? beat.orderIndex ?? 0,
        endInStoryDate: beat.endInStoryDate ?? null,
        endDateOrder: beat.endDateOrder ?? null,
        entityType: beat.entityType ?? null,
        entityId: beat.entityId ?? null,
        metadata: beat.metadata ? JSON.stringify(beat.metadata) : null,
        autoGenerated: false,
        createdAt: now,
        updatedAt: now,
    };
    await db.insert(storyBeats).values(value as any);
    return parseBeat({ ...value, metadata: value.metadata } as any);
}

export async function updateBeat(
    db: SQLiteDB,
    id: string,
    data: Partial<NewStoryBeat>
): Promise<StoryBeat | undefined> {
    const updateData: Record<string, unknown> = { updatedAt: new Date() };
    const fields: Array<keyof NewStoryBeat> = [
        'projectId',
        'chapterId',
        'beatType',
        'title',
        'description',
        'orderIndex',
        'inStoryDate',
        'dateOrder',
        'endInStoryDate',
        'endDateOrder',
        'entityType',
        'entityId',
        'eventType',
    ];
    for (const field of fields) {
        if (data[field] !== undefined) updateData[field] = data[field] as any;
    }
    if (data.metadata !== undefined)
        updateData.metadata = data.metadata
            ? JSON.stringify(data.metadata)
            : null;
    await db.update(storyBeats).set(updateData).where(eq(storyBeats.id, id));
    return getBeatById(db, id);
}

export async function deleteBeat(db: SQLiteDB, id: string): Promise<void> {
    await db.delete(storyBeats).where(eq(storyBeats.id, id));
}

export async function autoGenerateEvents(
    db: SQLiteDB,
    projectId: string
): Promise<number> {
    let count = 0;
    const existingAuto = await db
        .select({ id: storyBeats.id })
        .from(storyBeats)
        .where(
            and(
                eq(storyBeats.projectId, projectId),
                eq(storyBeats.autoGenerated, true)
            )
        );
    const existingAutoIds = new Set(existingAuto.map((r) => r.id));

    const chapterRows = await db
        .select()
        .from(chapters)
        .where(eq(chapters.projectId, projectId))
        .orderBy(asc(chapters.orderIndex));
    const charRows = await db
        .select()
        .from(characters)
        .where(eq(characters.projectId, projectId))
        .orderBy(asc(characters.name));
    const orgRows = await db
        .select()
        .from(organizations)
        .where(eq(organizations.projectId, projectId))
        .orderBy(asc(organizations.name));

    const upsert = async (row: Record<string, unknown>) => {
        await db
            .insert(storyBeats)
            .values(row as any)
            .onConflictDoUpdate({
                target: storyBeats.id,
                set: {
                    title: row.title,
                    dateOrder: row.dateOrder,
                    orderIndex: row.orderIndex,
                    chapterId: row.chapterId,
                    entityType: row.entityType,
                    entityId: row.entityId,
                    eventType: row.eventType,
                    autoGenerated: true,
                    updatedAt: new Date(),
                } as any,
            });
        count++;
    };

    for (const chapter of chapterRows) {
        const eventId = `auto-chapter-${chapter.id}`;
        if (!existingAutoIds.delete(eventId)) {
            await upsert({
                id: eventId,
                projectId,
                title: chapter.title,
                description: null,
                chapterId: chapter.id,
                beatType: 'custom',
                orderIndex: chapter.orderIndex,
                inStoryDate: null,
                dateOrder: chapter.orderIndex,
                endInStoryDate: null,
                endDateOrder: null,
                entityType: null,
                entityId: null,
                eventType: 'chapter',
                metadata: null,
                autoGenerated: true,
                createdAt: new Date(),
                updatedAt: new Date(),
            });
        }
    }

    for (const ch of charRows) {
        const eventId = `auto-char-${ch.id}`;
        if (!existingAutoIds.delete(eventId)) {
            await upsert({
                id: eventId,
                projectId,
                title: `Character introduced: ${ch.name}`,
                description: null,
                chapterId: null,
                beatType: 'custom',
                orderIndex: -1000,
                inStoryDate: null,
                dateOrder: -1000,
                endInStoryDate: null,
                endDateOrder: null,
                entityType: 'character',
                entityId: ch.id,
                eventType: 'character_introduction',
                metadata: null,
                autoGenerated: true,
                createdAt: ch.createdAt,
                updatedAt: new Date(),
            });
        }
    }

    for (const org of orgRows) {
        const eventId = `auto-org-${org.id}`;
        if (!existingAutoIds.delete(eventId)) {
            await upsert({
                id: eventId,
                projectId,
                title: `Organization founded: ${org.name}`,
                description: null,
                chapterId: null,
                beatType: 'custom',
                orderIndex: -999,
                inStoryDate: null,
                dateOrder: -999,
                endInStoryDate: null,
                endDateOrder: null,
                entityType: 'organization',
                entityId: org.id,
                eventType: 'organization_founding',
                metadata: null,
                autoGenerated: true,
                createdAt: org.createdAt,
                updatedAt: new Date(),
            });
        }
    }

    for (const id of existingAutoIds) await deleteBeat(db, id);
    return count;
}
